"""A2UI v1.0 protocol envelopes; restricted application catalog, not official SDK."""
from uuid import uuid4
from typing import Any
from .data import INVOICES, REVENUE

VERSION = "v1.0"
CATALOG_ID = "https://example.org/catalogs/accounting/v2.json"  # demo identifier, not a live URL
APPROVED = {"Column", "Text", "Table", "Card", "Chart"}
UNSAFE_KEYS = {"__proto__", "constructor", "prototype"}
ALLOWED_PROPS = {
    "Column": {"children"}, "Text": {"text"}, "Table": {"columns", "rows"},
    "Card": {"metrics"}, "Chart": {"chartType", "rows", "xKey", "yKey", "unit"},
}


def component_messages(kind: str, dataset: str, title: str) -> list[dict[str, Any]]:
    """Create protocol envelopes for selected component; data never generated by LLM."""
    if kind not in {"table", "card", "chart"} or dataset not in {"invoices", "revenue"}:
        raise ValueError("Unknown UI selection")
    if kind == "chart" and dataset != "revenue": raise ValueError("Chart requires revenue")
    if kind == "card" and dataset != "invoices": raise ValueError("Card requires invoices")
    if not isinstance(title, str) or not (1 <= len(title) <= 100): raise ValueError("Invalid title")
    surface_id = f"finance_{uuid4().hex}"
    if kind == "table":
        component = {"id": "visual", "component": "Table", "rows": {"path": "/rows"},
                     "columns": [{"key": k, "label": label} for k, label in [
                         ("number", "Invoice"), ("customer", "Customer"),
                         ("amount", "Amount"), ("currency", "Currency"), ("status", "Status")
                     ]] if dataset == "invoices" else [{"key": "month", "label": "Month"}, {"key": "revenue", "label": "Revenue (DKK)"}]}
        rows = INVOICES if dataset == "invoices" else REVENUE
        data = {"rows": rows}
    elif kind == "card":
        total = sum(r["amount"] for r in INVOICES)
        unpaid = sum(r["amount"] for r in INVOICES if r["status"] == "unpaid")
        component = {"id": "visual", "component": "Card", "metrics": [
            {"label": "Invoices", "value": {"path": "/count"}, "suffix": ""},
            {"label": "Total", "value": {"path": "/total"}, "suffix": " DKK"},
            {"label": "Unpaid", "value": {"path": "/unpaid"}, "suffix": " DKK"},
        ]}
        data = {"count": len(INVOICES), "total": total, "unpaid": unpaid}
    else:
        component = {"id": "visual", "component": "Chart", "chartType": "bar",
                     "rows": {"path": "/rows"}, "xKey": "month", "yKey": "revenue", "unit": "DKK"}
        data = {"rows": REVENUE}
    return [
        {"version": VERSION, "createSurface": {"surfaceId": surface_id, "catalogId": CATALOG_ID}},
        {"version": VERSION, "updateComponents": {"surfaceId": surface_id, "components": [
            {"id": "root", "component": "Column", "children": ["heading", "visual"]},
            {"id": "heading", "component": "Text", "text": title}, component]}},
        {"version": VERSION, "updateDataModel": {"surfaceId": surface_id, "path": "/", "value": data}},
    ]


def validate_a2ui(message: dict[str, Any]) -> None:
    if message.get("version") != VERSION: raise ValueError("Unsupported A2UI version")
    keys = set(message) - {"version"}
    if len(keys) != 1 or next(iter(keys)) not in {"createSurface", "updateComponents", "updateDataModel", "deleteSurface"}:
        raise ValueError("Invalid A2UI envelope")
    kind = next(iter(keys)); payload = message[kind]
    if not isinstance(payload, dict) or not isinstance(payload.get("surfaceId"), str): raise ValueError("Missing surface ID")
    if kind == "createSurface" and payload.get("catalogId") != CATALOG_ID: raise ValueError("Untrusted catalog")
    if kind == "updateDataModel":
        path = payload.get("path", "/")
        if not isinstance(path, str) or (path != "/" and not path.startswith("/")): raise ValueError("Invalid data path")
        if any(t in UNSAFE_KEYS for t in path.split("/")): raise ValueError("Unsafe data path")
    if kind == "updateComponents":
        components = payload.get("components")
        if not isinstance(components, list) or len(components) > 20: raise ValueError("Invalid component list")
        ids = [c.get("id") for c in components]
        if "root" not in ids or len(ids) != len(set(ids)): raise ValueError("Invalid IDs")
        if any(not isinstance(c, dict) or c.get("component") not in APPROVED for c in components): raise ValueError("Unapproved component")
        for c in components: _validate_component(c, set(ids))


def _binding(value: Any) -> None:
    if not isinstance(value, dict) or set(value) != {"path"}: raise ValueError("Invalid data binding")
    path = value["path"]
    if not isinstance(path, str) or not path.startswith("/"): raise ValueError("Invalid data binding")
    if any(t in UNSAFE_KEYS for t in path.split("/")): raise ValueError("Unsafe data path")


def _text(value: Any, limit: int = 100) -> None:
    if not isinstance(value, str) or len(value) > limit: raise ValueError("Invalid text property")


def _validate_component(c: dict[str, Any], ids: set[str]) -> None:
    """Property-level checks for the approved components; unknown properties are rejected."""
    kind = c["component"]
    if set(c) - ALLOWED_PROPS[kind] - {"id", "component"}: raise ValueError("Unexpected component property")
    if kind == "Column":
        children = c.get("children", [])
        if not isinstance(children, list) or len(children) > 20 or any(ch not in ids for ch in children):
            raise ValueError("Invalid children")
    elif kind == "Text":
        _text(c.get("text"), 200)
    elif kind == "Table":
        columns = c.get("columns")
        if not isinstance(columns, list) or len(columns) > 20: raise ValueError("Invalid columns")
        for col in columns:
            if not isinstance(col, dict): raise ValueError("Invalid column")
            _text(col.get("key")); _text(col.get("label"))
        _binding(c.get("rows"))
    elif kind == "Card":
        metrics = c.get("metrics")
        if not isinstance(metrics, list) or len(metrics) > 8: raise ValueError("Invalid metrics")
        for m in metrics:
            if not isinstance(m, dict): raise ValueError("Invalid metric")
            _text(m.get("label")); _text(m.get("suffix", "")); _binding(m.get("value"))
    elif kind == "Chart":
        if c.get("chartType") != "bar": raise ValueError("Unknown chart kind")
        _binding(c.get("rows")); _text(c.get("xKey")); _text(c.get("yKey")); _text(c.get("unit", ""), 20)
